export function localized<T extends string | undefined>(value: { en: T; he?: T } | T, locale: Locale): T {
  if (value && typeof value === "object") {
    const v = value as { en: T; he?: T };
    return (locale === "he" && v.he !== undefined && v.he !== "" ? v.he : v.en) as T;
  }
  return value as T;
}
