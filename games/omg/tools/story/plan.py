"""Timeline of the Genesis narration: where every phrase starts, for the soundtrack
mixer (plan_<lang>.json) and for the game (src/story_data.rs)."""
import json, os, sys, wave, unicodedata
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verses
HERE = os.path.dirname(os.path.abspath(__file__))
D = os.environ.get('OMG_NARR_WORK', os.path.join(HERE, 'work'))
LEAD, IN_VERSE, BETWEEN, AFTER_DAY, TAIL = 4.2, 0.5, 1.05, 3.4, 7.0
def dur(path):
    with wave.open(path) as w: return w.getnframes() / w.getframerate()
def plan(lang, src_dir):
    wlc = json.load(open(os.path.join(HERE, 'genesis_he.json'), encoding='utf-8'))
    t = LEAD
    verses_out, phrases = [], []
    for vi, (ref, he, ph, en) in enumerate(verses.V):
        texts = en if lang == 'en' else None
        if lang == 'he':
            # display text in the codex's own mark order, split where the reading splits
            words = ' '.join(wlc[vi]['he']).split(' ')
            texts, k = [], 0
            for p in he:
                n = len(p.split(' ')); texts.append(' '.join(words[k:k + n])); k += n
            assert k == len(words), ref
        if vi == 2: t += 2.2          # darkness before "Let there be light"
        v0 = t; p0 = len(phrases)
        for pi, txt in enumerate(texts):
            f = f'{src_dir}/v{vi:02d}p{pi}.wav'
            d = dur(f)
            phrases.append({'t0': round(t, 3), 't1': round(t + d, 3), 'text': txt, 'file': f})
            t += d
            if pi < len(texts) - 1:
                t += IN_VERSE
                if vi == 2 and pi == 0: t += 1.5      # "...Let there be light." — then light
                if vi == 8 and pi == 0: t += 0.6      # a breath before the dry land appears (the player raises it)
                if vi == 15 and pi == 0: t += 0.6     # …and before the sun is lit
                if vi == 30 and pi == 1: t += 1.2     # "…it was very good."
        day_end = vi in (4, 7, 12, 18, 22, 30)
        verses_out.append({'c': ref[0], 'v': ref[1], 'day': verses.day_of(ref), 't0': round(v0, 3), 't1': round(t, 3), 'p0': p0, 'n': len(texts), 'day_end': day_end})
        t += AFTER_DAY if day_end else BETWEEN
    total = t - BETWEEN + TAIL
    return {'lang': lang, 'len': round(total, 3), 'verses': verses_out, 'phrases': phrases}
def rs_str(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def emit(tracks, out):
    o = ['// Generated by tools/story/plan.py from the narration recordings — do not edit.', '']
    for name, p in tracks:
        o.append(f'pub static {name}: Track = Track {{ len: {p["len"]:.3f}, verses: &[')
        for v in p['verses']:
            o.append(f'    Verse {{ c: {v["c"]}, v: {v["v"]}, day: {v["day"]}, t0: {v["t0"]:.3f}, t1: {v["t1"]:.3f}, p0: {v["p0"]}, n: {v["n"]} }},')
        o.append('], phrases: &[')
        for ph in p['phrases']:
            o.append(f'    Phrase {{ t0: {ph["t0"]:.3f}, t1: {ph["t1"]:.3f}, text: {rs_str(ph["text"])} }},')
        o.append('] };')
        o.append('')
    open(out, 'w', encoding='utf-8').write('\n'.join(o))
def cues(p):
    V, P = p['verses'], p['phrases']
    ph = lambda vi, pi: P[V[vi]['p0'] + (pi if pi >= 0 else V[vi]['n'] + pi)]
    c = [('len', p['len'])]
    c.append(('light', ph(2, -1)['t0']))
    for k, vi in enumerate([4, 7, 12, 18, 22, 30], start=1): c.append((f'day_end{k}', ph(vi, -1)['t1']))
    starts = {}
    for v in V: starts.setdefault(v['day'], v['t0'])
    for d in range(8): c.append((f'day{d}', starts[d]))
    # the moments of creation the game waits for (src/story.rs beat_times) are the
    # light, firmament, land, sun, fish, beasts, people and candles cues
    moon = ph(15, 2)['t0'] if V[15]['n'] >= 4 else ph(15, 1)['t0'] + (ph(15, 1)['t1'] - ph(15, 1)['t0']) * 0.55
    c += [('spirit', ph(1, -1)['t0']), ('firmament', V[6]['t0']), ('land', ph(8, 1)['t0']), ('plants', V[10]['t0'] + 0.5),
          ('sun', ph(15, 1)['t0']), ('moon', moon), ('stars', ph(15, -1)['t0']),
          ('fish', V[20]['t0']), ('birds', V[20]['t0'] + 2.0), ('whale', V[20]['t0'] + 0.4), ('beasts', V[24]['t0']),
          ('people', V[26]['t0']), ('good', ph(30, 1)['t0']), ('rest', V[31]['t0']), ('candles', V[33]['t0']), ('blessed', V[33]['t0'] + 0.5)]
    return c
def write_txt(p, path):
    # a phrase read by another voice can carry its own pitch shift: <recordings>/shift.json {"v02p0.wav": 1.4}
    shifts = {}
    for ph in p['phrases']:
        d = os.path.dirname(ph['file'])
        if d not in shifts: shifts[d] = json.load(open(os.path.join(d, 'shift.json'))) if os.path.exists(os.path.join(d, 'shift.json')) else {}
    with open(path, 'w', encoding='utf-8') as f:
        for k, v in cues(p): f.write(f'cue {k} {v:.3f}\n')
        for ph in p['phrases']:
            ds = shifts[os.path.dirname(ph['file'])].get(os.path.basename(ph['file']))
            f.write(f"phrase {ph['t0']:.3f} {ph['file']}" + (f' {ds}' if ds else '') + '\n')
if __name__ == '__main__':
    tracks = []
    for lang, name in (('en', 'EN'), ('he', 'HE')):
        src = f'{D}/{lang}'
        if not os.path.isdir(src): continue
        p = plan(lang, src)
        json.dump(p, open(f'{D}/plan_{lang}.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        write_txt(p, f'{D}/plan_{lang}.txt')
        tracks.append((name, p))
        print(lang, 'length %.1fs' % p['len'], len(p['phrases']), 'phrases')
    if len(tracks) == 1:  # a language without its own recording falls back to English timing
        tracks.append(('HE' if tracks[0][0] == 'EN' else 'EN', tracks[0][1]))
    emit(tracks, sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'src', 'story_data.rs'))
